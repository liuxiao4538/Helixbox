#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
把 helixbox 源码打包成多架构、双格式安装包：
  - 24.10 及更早（opkg）  -> .ipk   (ar: debian-binary + control.tar.gz + data.tar.gz)
  - 25.12 及更新（apk-tools）-> .apk   (control.tar.gz + data.tar.gz 直接拼接，.PKGINFO 里 arch=noarch)

用法：python3 build_packages.py
产物结构：
  dist/ipk/<arch>/luci-app-helixbox_1.0.0_<arch>.ipk
  dist/apk/<arch>/luci-app-helixbox-1.0.0-r1.apk
  dist/noarch/...            （通用包：ipk 用 all，apk 用 noarch）
本机无需 OpenWrt SDK。
"""
import os
import io
import tarfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
DIST = os.path.join(HERE, "dist")
VERSION = "1.0.0"
PKG_REV = "r1"

# 支持架构（目录名遵循 OpenWrt 官方拼写）
ARCHS = [
    "x86_64",
    "aarch64_cortex-a53",
    "aarch64_cortex-a72",
    "arm_cortex-a7_neon-vfpv4",
]

DATA_FILES = [
    ("luasrc/controller/helixbox.lua",      "usr/lib/lua/luci/controller/helixbox.lua", 0o644),
    ("luasrc/model/cbi/helixbox.lua",       "usr/lib/lua/luci/model/cbi/helixbox.lua", 0o644),
    ("luasrc/view/helixbox/status.htm",     "usr/lib/lua/luci/view/helixbox/status.htm", 0o644),
    ("root/etc/config/helixbox",            "etc/config/helixbox", 0o644),
    ("root/etc/init.d/helixbox",            "etc/init.d/helixbox", 0o755),
    ("root/usr/sbin/helixbox-ctl",          "usr/sbin/helixbox-ctl", 0o755),
    ("root/usr/sbin/helixbox-speedtest",    "usr/sbin/helixbox-speedtest", 0o755),
    ("root/usr/share/helixbox/iplist.txt",  "usr/share/helixbox/iplist.txt", 0o644),
]

DESC_SHORT = "Helixbox download accelerator with LuCI GUI and v3 speed test"
DESC_LONG = (
    "Helixbox accelerates Xbox / Microsoft Store / PS / NS downloads by redirecting "
    "xboxlive.com domains to the domestic CDN. Includes a v3-style concurrent speed "
    "test engine running on the router and a graphical LuCI status page."
)
DEPS = ["libc", "luci-base", "lighttpd", "lighttpd-mod-redirect",
        "lighttpd-mod-proxy", "curl", "iputils-ping"]


def make_tar_gz(entries):
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w:gz", format=tarfile.GNU_FORMAT) as tf:
        for arcname, data, mode in entries:
            info = tarfile.TarInfo("./" + arcname)
            info.size = len(data)
            info.mode = mode
            info.mtime = 0
            info.uid = 0
            info.gid = 0
            info.uname = "root"
            info.gname = "root"
            tf.addfile(info, io.BytesIO(data))
    return raw.getvalue()


def build_data():
    entries = []
    for src, dst, mode in DATA_FILES:
        with open(os.path.join(HERE, src), "rb") as fh:
            entries.append((dst, fh.read(), mode))
    return entries


def control_text(arch):
    return ("Package: luci-app-helixbox\n"
            f"Version: {VERSION}\n"
            "Depends: " + ", ".join(DEPS) + "\n"
            "Source: package/helixbox\n"
            "Maintainer: Helixbox\n"
            f"Architecture: {arch}\n"
            "Installed-Size: 128\n"
            f"Description: {DESC_SHORT}\n"
            " " + DESC_LONG + "\n")


def pkginfo_text():
    # apk 规定：通用包写 noarch，写 all 会装不上
    return ("# Generated by build_packages.py\n"
            f"pkgname = luci-app-helixbox\n"
            f"pkgver = {VERSION}-{PKG_REV}\n"
            "pkgdesc = " + DESC_SHORT + "\n"
            "arch = noarch\n"
            "origin = helixbox\n"
            "maintainer = Helixbox\n"
            "url = https://github.com/liuxiao4538/Helixbox\n"
            "depends = " + " ".join(DEPS) + "\n"
            "dataSize = 1\n")


def ar_header(name, size):
    return (name.ljust(16)[:16]
            + str(int(time.time())).ljust(12)[:12]
            + "0".ljust(6) + "0".ljust(6)
            + "100644".ljust(8)[:8]
            + str(size).ljust(10)[:10]
            + "`\n").encode("ascii")


def write_ar(path, members):
    with open(path, "wb") as f:
        f.write(b"!<arch>\n")
        for name, data in members:
            f.write(ar_header(name, len(data)))
            f.write(data)
            if len(data) % 2:
                f.write(b"\n")


def build_ipk(arch, data_entries):
    out_dir = os.path.join(DIST, "ipk", arch)
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, f"luci-app-helixbox_{VERSION}_{arch}.ipk")
    control = make_tar_gz([("control", control_text(arch).encode("utf-8"), 0o644)])
    data = make_tar_gz(data_entries)
    write_ar(out, [("debian-binary", b"2.0\n"), ("control.tar.gz", control), ("data.tar.gz", data)])
    return out


def build_apk(arch, data_entries):
    out_dir = os.path.join(DIST, "apk", arch)
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, f"luci-app-helixbox-{VERSION}-{PKG_REV}.apk")
    control = make_tar_gz([(".PKGINFO", pkginfo_text().encode("utf-8"), 0o644)])
    data = make_tar_gz(data_entries)
    with open(out, "wb") as f:
        f.write(control)   # apk: 两个 gzipped tar 直接拼接
        f.write(data)
    return out


def main():
    missing = [s for s, _, _ in DATA_FILES if not os.path.isfile(os.path.join(HERE, s))]
    if missing:
        raise SystemExit("缺少文件: " + ", ".join(missing))
    data_entries = build_data()
    made = []
    for arch in ARCHS:
        made.append(build_ipk(arch, data_entries))
        made.append(build_apk(arch, data_entries))
    # 通用包（ipk=all / apk=noarch）—— 纯脚本一份通吃
    made.append(build_ipk("all", data_entries))
    made.append(build_apk("noarch", data_entries))
    print(f"生成 {len(made)} 个包：")
    for p in made:
        print(f"  {os.path.relpath(p, DIST)}  ({os.path.getsize(p)/1024:.1f} KB)")


if __name__ == "__main__":
    main()
